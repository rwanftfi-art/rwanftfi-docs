/**
 * Detect language from the current URL path.
 * Mintlify uses /{lang}/page-name pattern.
 * Returns 'en' as default.
 */
export function useLang() {
  if (typeof window === 'undefined') return 'en';
  var match = window.location.pathname.match(/^\/(en|es|ru|ar|zh|tr)\//);
  return match ? match[1] : 'en';
}

/**
 * Get a translated string by key.
 * Falls back to English if the key is missing for the detected language.
 */
export function t(lang, key) {
  var dict = translations[lang] || translations.en;
  return dict[key] !== undefined ? dict[key] : (translations.en[key] !== undefined ? translations.en[key] : key);
}
